/* rhythm notation tokens: w h q e s (+ "." dotted, "r" rest, "t" = triplet eighth). value in quarter beats */
const DUR = { w: 4, h: 2, q: 1, e: .5, s: .25, t: 1 / 3 };
function parseRhythm(str) {
  return str.trim().split(/\s+/).map(tok => {
    const m = /^([whqest])(\.?)(r?)(>?)$/.exec(tok); if (!m) return null;
    let d = DUR[m[1]]; if (m[2]) d *= 1.5; return { k: m[1], dot: !!m[2], rest: !!m[3], acc: !!m[4], d };
  }).filter(Boolean);
}
function rhythmOnsets(tokens) { let t = 0; const out = []; for (const k of tokens) { if (!k.rest) out.push({ t, acc: k.acc }); t += k.d } return { hits: out, len: t } }
